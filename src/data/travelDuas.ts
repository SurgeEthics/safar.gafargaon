// Helper to format exact copy text for clipboard
export function formatDuaForCopy(dua: {
  title: string;
  subTitle?: string;
  arabic?: string;
  transliteration?: string;
  translation?: string;
  narration?: string;
  context?: string;
  reference?: string;
}): string {
  const parts: string[] = [];
  parts.push(dua.title);
  if (dua.subTitle) parts.push(dua.subTitle);
  if (dua.narration) parts.push(dua.narration);
  if (dua.arabic) parts.push(dua.arabic);
  if (dua.transliteration) parts.push(`উচ্চারণ: "${dua.transliteration}"`);
  if (dua.translation) parts.push(`অর্থ: "${dua.translation}"`);
  if (dua.context) parts.push(dua.context);
  if (dua.reference) parts.push(dua.reference);
  return parts.join('\n\n');
}
