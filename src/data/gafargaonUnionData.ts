// Helper to filter places by union ID
export function getPlacesByUnion(unionId: string): ComprehensivePlace[] {
  return COMPREHENSIVE_UNION_PLACES.filter(p => p.unionId === unionId);
}

// Helper to filter only stands
export function getAllStands(): ComprehensivePlace[] {
  return COMPREHENSIVE_UNION_PLACES.filter(p => p.isStand);
}

// Search utility matching Bengali, English and keywords
export function searchComprehensivePlaces(query: string): ComprehensivePlace[] {
  if (!query || !query.trim()) return COMPREHENSIVE_UNION_PLACES;
  const q = query.toLowerCase().trim();
  return COMPREHENSIVE_UNION_PLACES.filter(place => {
    return (
      place.bengaliName.toLowerCase().includes(q) ||
      place.name.toLowerCase().includes(q) ||
      place.area.toLowerCase().includes(q) ||
      place.unionNameBengali.toLowerCase().includes(q) ||
      place.category.toLowerCase().includes(q) ||
      place.searchKeywords.some(kw => kw.toLowerCase().includes(q) || q.includes(kw.toLowerCase()))
    );
  });
}
